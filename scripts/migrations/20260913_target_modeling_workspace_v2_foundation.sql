CREATE OR REPLACE FUNCTION public.get_ti_capabilities()
RETURNS TABLE (
  enabled BOOLEAN,
  access_mode TEXT,
  chat_layout TEXT,
  target_modeling_workspace_v2 BOOLEAN,
  public_daily_analyses INTEGER,
  authenticated_daily_analyses INTEGER,
  max_uploads_per_analysis INTEGER,
  max_upload_bytes BIGINT
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT settings.enabled, settings.access_mode, settings.chat_layout,
    settings.target_modeling_workspace_v2, settings.public_daily_analyses,
    settings.authenticated_daily_analyses, settings.max_uploads_per_analysis,
    settings.max_upload_bytes
  FROM public.ti_admin_settings AS settings
  WHERE settings.setting_key = 'global'
  LIMIT 1;
$$;

