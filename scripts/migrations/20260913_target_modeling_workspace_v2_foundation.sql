CREATE OR REPLACE FUNCTION public.can_access_ti_workspace(
  p_workspace_id UUID,
  p_roles TEXT[] DEFAULT NULL
)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT
    EXISTS (
      SELECT 1 FROM public.ti_workspaces AS workspace
      WHERE workspace.id = p_workspace_id
        AND workspace.user_id = (SELECT auth.uid())
        AND workspace.deleted_at IS NULL
    )
    OR COALESCE(public.is_admin(), FALSE)
    OR EXISTS (
      SELECT 1 FROM public.ti_workspace_members AS member
      WHERE member.workspace_id = p_workspace_id
        AND member.user_id = (SELECT auth.uid())
        AND member.accepted_at IS NOT NULL
        AND member.revoked_at IS NULL
        AND (p_roles IS NULL OR member.role = ANY (p_roles))
    );
$$;

REVOKE ALL ON FUNCTION public.can_access_ti_workspace(UUID, TEXT[]) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.can_access_ti_workspace(UUID, TEXT[]) TO authenticated;

INSERT INTO public.ti_workspace_members (workspace_id, user_id, role, invited_by, accepted_at)
SELECT workspace.id, workspace.user_id, 'owner', workspace.user_id, workspace.created_at
FROM public.ti_workspaces AS workspace
ON CONFLICT (workspace_id, user_id) DO NOTHING;

CREATE OR REPLACE FUNCTION public.create_ti_workspace_owner_membership()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  INSERT INTO public.ti_workspace_members (
    workspace_id, user_id, role, invited_by, accepted_at
  ) VALUES (
    NEW.id, NEW.user_id, 'owner', NEW.user_id, NOW()
  )
  ON CONFLICT (workspace_id, user_id) DO UPDATE
    SET role = 'owner', accepted_at = COALESCE(public.ti_workspace_members.accepted_at, EXCLUDED.accepted_at), revoked_at = NULL;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.create_ti_workspace_owner_membership() FROM PUBLIC;
DROP TRIGGER IF EXISTS ti_workspaces_create_owner_membership ON public.ti_workspaces;
CREATE TRIGGER ti_workspaces_create_owner_membership
  AFTER INSERT ON public.ti_workspaces
  FOR EACH ROW EXECUTE FUNCTION public.create_ti_workspace_owner_membership();

